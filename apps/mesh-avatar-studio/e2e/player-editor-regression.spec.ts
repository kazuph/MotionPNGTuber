import { test, expect } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
test.setTimeout(120000);
test.use({ channel: 'chrome', viewport: { width: 1600, height: 1100 }, launchOptions: { args: ['--mute-audio'] } });
test('the original editor opens dokochan bust and preserves pose and reload controls', async ({ page }) => {
  const errors: string[] = [], httpErrors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => { if (r.status() >= 400 && !r.url().endsWith('/favicon.ico')) httpErrors.push(`${r.status()} ${r.url()}`); });
  await page.goto('/');
  const guide = page.getByTestId('first-guide'); if (await guide.isVisible()) await guide.getByRole('button').click();
  await page.getByText('Open project', { exact: true }).click();
  await page.getByTestId('project-dokochan-bust').click();
  await expect(page.getByTestId('preview-status')).toHaveAttribute('data-state', 'ready', { timeout: 30000 });
  await page.getByTestId('idle-toggle').click();
  await expect(page.getByTestId('idle-toggle')).toHaveAttribute('aria-pressed', 'false');
  const canvas = page.getByTestId('preview');
  const hash = async () => createHash('sha256').update(await canvas.evaluate(node => (node as HTMLCanvasElement).toDataURL())).digest('hex');
  await page.getByRole('tab', { name: 'Pose test', exact: true }).click();
  const rest = await hash();
  await page.getByRole('slider', { name: 'Turn left/right', exact: true }).focus();
  await page.getByRole('slider', { name: 'Turn left/right', exact: true }).press('End');
  await expect.poll(hash).not.toBe(rest); const turn = await hash();
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  await page.getByRole('slider', { name: 'Mouth open', exact: true }).focus();
  await page.getByRole('slider', { name: 'Mouth open', exact: true }).press('End');
  await expect.poll(hash).not.toBe(rest); const mouth = await hash();
  await page.screenshot({ path: 'projects/dokochan-bust/review/player/editor-regression.png', fullPage: true });
  await page.reload();
  await expect(page.getByTestId('preview-status')).toHaveAttribute('data-state', 'ready', { timeout: 30000 });
  await page.getByTestId('part-head').click();
  await expect(page.getByRole('spinbutton', { name: 'head.cx', exact: true })).toHaveValue('635');
  expect(errors).toEqual([]); expect(httpErrors).toEqual([]);
  await writeFile('projects/dokochan-bust/review/player/editor-regression.json', JSON.stringify({ rest, turn, mouth, reloadHeadCenter: 635, pageErrors: errors, httpErrors, source: 'real editor localhost routes; no rig save or asset write' }, null, 2));
});
